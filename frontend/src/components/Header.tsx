import type { Meta } from '../types'
import { fmtDate } from '../lib/format'
import { formatInstant, TIMEZONES, tzLabel } from '../lib/time'

export default function Header({
  meta, preset, onPreset, custom, onCustom, property, onProperty, onRefresh,
  tz, onTz,
}: {
  meta: Meta | null
  preset: string
  onPreset: (key: string) => void
  custom: { start: string; end: string }
  onCustom: (range: { start: string; end: string }) => void
  property: string
  onProperty: (slug: string) => void
  onRefresh: () => void
  tz: string
  onTz: (tz: string) => void
}) {
  const presets = ['thisWeek', 'lastWeek', 'last4', 'last12', 'all', 'custom']
  const labels: Record<string, string> = {
    thisWeek: 'This week', lastWeek: 'Last week', last4: 'Last 4 weeks',
    last12: 'Last 12 weeks', all: 'All time', custom: 'Custom',
  }

  const activeChip = 'bg-indigo-600 text-white'
  const idleChip = 'bg-slate-100 text-slate-600 hover:bg-slate-200'
  const chipBtn = 'inline-flex shrink-0 items-center rounded-full px-3.5 py-2 text-xs font-medium whitespace-nowrap'

  return (
    <header className="border-b border-slate-200 bg-white">
      <div className="mx-auto max-w-7xl px-4 py-4 sm:px-6 sm:py-5">
        <div className="flex flex-wrap items-start justify-between gap-3">
          <div className="min-w-0">
            <h1 className="text-lg font-bold text-slate-900 sm:text-xl">
              Azzurro Hotels · Guest Review Dashboard
            </h1>
            <p className="mt-1 text-sm text-slate-500">
              Booking.com guest reviews across {meta?.properties.length ?? 4} properties
              {meta?.date_range.start && (
                <> · {meta.total_reviews.toLocaleString()} reviews
                  <span className="hidden sm:inline">
                    {' '}({fmtDate(meta.date_range.start)} – {fmtDate(meta.date_range.end)})
                  </span></>
              )}
            </p>
          </div>
          <div className="flex items-center gap-2">
            {meta?.classification && (
              <span
                className="chip hidden bg-slate-100 text-slate-500 sm:inline-flex"
                title={
                  (meta.classification.llm ?? 0) > 0
                    ? `AI-assisted classification: ${meta.classification.llm ?? 0} reviews LLM-tagged, ${meta.classification.keyword ?? 0} keyword-tagged`
                    : 'Topic tags are generated by keyword (lexical) analysis — approximate by nature. Set LLM_API_KEY to enable AI-assisted tagging.'
                }>
                {(meta.classification.llm ?? 0) > 0
                  ? `AI-assisted tags (${meta.classification.llm ?? 0})`
                  : 'Keyword-based tags'}
              </span>
            )}
            {meta?.last_scrape_run && (
              <span
                className="chip hidden bg-slate-100 text-slate-500 sm:inline-flex"
                title={`Last scrape: ${meta.last_scrape_run.mode}, ${meta.last_scrape_run.status} · shown in ${tzLabel(tz)}`}>
                Latest data: {formatInstant(meta.last_scrape_run.finished_at, tz)}
              </span>
            )}
            <select
              value={tz}
              onChange={(e) => onTz(e.target.value)}
              title="Display timezone — also sets which day counts as 'today' for weekly stats"
              className="rounded-lg border border-slate-200 bg-white px-2 py-2 text-xs font-medium text-slate-600 hover:bg-slate-50">
              {TIMEZONES.map((t) => (
                <option key={t.key} value={t.key}>{t.label}</option>
              ))}
            </select>
            <button onClick={onRefresh}
              className="rounded-lg border border-slate-200 px-3 py-2 text-sm font-medium text-slate-600 hover:bg-slate-50">
              Refresh
            </button>
          </div>
        </div>

        {/* Compact info line on mobile (chips above are desktop-only) */}
        {(meta?.classification || meta?.last_scrape_run) && (
          <p className="mt-1.5 flex flex-wrap gap-x-3 text-[11px] text-slate-400 sm:hidden">
            {meta?.classification && (
              <span>
                {(meta.classification.llm ?? 0) > 0
                  ? `AI-assisted tags (${meta.classification.llm ?? 0})`
                  : 'Keyword-based tags'}
              </span>
            )}
            {meta?.last_scrape_run && (
              <span>
                Data updated {formatInstant(meta.last_scrape_run.finished_at, tz)}
              </span>
            )}
          </p>
        )}

        {/* Filters: horizontally scrollable chip strips on narrow screens */}
        <div className="mt-3 space-y-2.5">
          <div>
            <span className="text-[10px] font-semibold uppercase tracking-wider text-slate-400">
              Properties
            </span>
            <div className="scroll-x -mx-4 mt-1.5 px-4 sm:mx-0 sm:px-0">
              <div className="flex w-max items-center gap-2 pb-0.5">
                <button onClick={() => onProperty('')}
                  className={`${chipBtn} ${property === '' ? activeChip : idleChip}`}>
                  All
                </button>
                {(meta?.properties ?? []).map((p) => (
                  <button key={p.slug} onClick={() => onProperty(p.slug)}
                    className={`${chipBtn} ${property === p.slug ? activeChip : idleChip}`}>
                    {p.name}
                  </button>
                ))}
              </div>
            </div>
          </div>

          <div>
            <span className="text-[10px] font-semibold uppercase tracking-wider text-slate-400">
              Period
            </span>
            <div className="scroll-x -mx-4 mt-1.5 px-4 sm:mx-0 sm:px-0">
              <div className="flex w-max items-center gap-2 pb-0.5">
                {presets.map((key) => (
                  <button key={key} onClick={() => onPreset(key)}
                    className={`${chipBtn} ${preset === key ? activeChip : idleChip}`}>
                    {labels[key]}
                  </button>
                ))}
              </div>
            </div>
            {preset === 'custom' && (
              <div className="mt-2 flex flex-wrap items-center gap-2 text-sm text-slate-500">
                <input type="date" value={custom.start} max={custom.end}
                  onChange={(e) => onCustom({ ...custom, start: e.target.value })}
                  className="rounded-lg border border-slate-200 px-2 py-2 text-sm" />
                <span>to</span>
                <input type="date" value={custom.end} min={custom.start}
                  onChange={(e) => onCustom({ ...custom, end: e.target.value })}
                  className="rounded-lg border border-slate-200 px-2 py-2 text-sm" />
              </div>
            )}
          </div>
        </div>
      </div>
    </header>
  )
}
